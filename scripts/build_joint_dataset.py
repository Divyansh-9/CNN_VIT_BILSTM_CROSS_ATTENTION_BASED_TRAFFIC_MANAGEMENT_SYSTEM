"""Compose BMD-45 and IDD into one training set, keeping the tests apart (S14).

    python scripts/build_joint_dataset.py --bmd45 data/bmd45_yolo --idd data/idd_yolo

**Why joint and not sequential.** Fine-tuning on BMD-45 and then on IDD ends
training on a corpus that is 100% dashcam, which is the exact geometry the S11
detector already over-fitted to — measured at mAP50 0.6201 on dashcam against
0.3223 on elevated CCTV. The last dataset a model sees is the one it believes.

**Why the test splits must NOT be merged, which is the whole point of this file.**
The question being asked is *"does adding elevated data fix elevated detection?"*
A union test set answers a different question and answers it misleadingly: it
reports one number dominated by whichever source contributed more images, so a
model could improve on dashcam, get worse on CCTV, and post a higher headline.

So this writes **three** configs:

    joint.yaml          train + val from BOTH        <- what training consumes
    eval_bmd45.yaml     test from BMD-45 only        <- elevated CCTV
    eval_idd.yaml       test from IDD only           <- dashcam

and every reported result names which one produced it. The dashcam figure is not
a formality: joint training could plausibly *cost* dashcam accuracy, and that
trade is a result worth having rather than one worth hiding.

**Nothing is copied.** Ultralytics accepts a list of image directories, so the
union is expressed in a config file rather than by duplicating gigabytes.
"""

from __future__ import annotations

import argparse
import collections
import sys
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parent.parent))

from scripts.prepare_idd import load_mapping  # noqa: E402


def census(root: Path, split: str, names: list[str]) -> collections.Counter:
    counts: collections.Counter = collections.Counter()
    directory = root / "labels" / split
    if not directory.is_dir():
        return counts
    for label in directory.glob("*.txt"):
        for line in label.read_text(encoding="utf-8").splitlines():
            if line.strip():
                counts[names[int(line.split()[0])]] += 1
    return counts


def write_yaml(path: Path, names: list[str], train, val, test) -> None:
    def render(value) -> str:
        if isinstance(value, list):
            return "\n" + "".join(f"  - {Path(v).resolve().as_posix()}\n" for v in value)
        return f" {Path(value).resolve().as_posix()}\n"

    path.parent.mkdir(parents=True, exist_ok=True)
    path.write_text(
        "# GENERATED by scripts/build_joint_dataset.py — do not edit.\n"
        f"train:{render(train)}"
        f"val:{render(val)}"
        f"test:{render(test)}"
        f"nc: {len(names)}\nnames: {names}\n",
        encoding="utf-8",
    )


def main(argv: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser(description=__doc__.split("\n")[0])
    parser.add_argument("--bmd45", type=Path, default=Path("data/bmd45_yolo"))
    parser.add_argument("--idd", type=Path, default=Path("data/idd_yolo"))
    parser.add_argument("--out", type=Path, default=Path("data/joint"))
    args = parser.parse_args(argv)

    names = load_mapping()["targets"]

    for root, label in ((args.bmd45, "bmd45"), (args.idd, "idd")):
        if not (root / "images" / "train").is_dir():
            raise SystemExit(
                f"{label} has no images/train at {root}. Build it first:\n"
                f"  python scripts/prepare_bmd45.py --count 8000\n"
                f"  python scripts/prepare_idd.py --count 8000 --copy-images"
            )

    write_yaml(
        args.out / "joint.yaml", names,
        train=[args.bmd45 / "images" / "train", args.idd / "images" / "train"],
        val=[args.bmd45 / "images" / "val", args.idd / "images" / "val"],
        # `test` here is never the reported figure; the two eval configs are.
        test=[args.bmd45 / "images" / "test", args.idd / "images" / "test"],
    )
    for label, root in (("bmd45", args.bmd45), ("idd", args.idd)):
        write_yaml(
            args.out / f"eval_{label}.yaml", names,
            train=root / "images" / "train",
            val=root / "images" / "val",
            test=root / "images" / "test",
        )

    print(f"  {'class':<16}{'BMD-45 train':>14}{'IDD train':>12}{'joint':>10}{'share':>9}")
    bmd = census(args.bmd45, "train", names)
    idd = census(args.idd, "train", names)
    total = sum(bmd.values()) + sum(idd.values())
    for name in names:
        a, b = bmd.get(name, 0), idd.get(name, 0)
        joint = a + b
        share = f"{100 * joint / total:.1f}%" if total else "—"
        print(f"  {name:<16}{a:>14,}{b:>12,}{joint:>10,}{share:>9}")
    print(f"  {'TOTAL':<16}{sum(bmd.values()):>14,}{sum(idd.values()):>12,}{total:>10,}")

    # An imbalance this large is not a defect, but it must be VISIBLE. BMD-45's
    # two-wheeler count dwarfs IDD's pedestrians, and the classes that exist in
    # only one source are the ones most at risk of being drowned.
    only_idd = [n for n in names if idd.get(n, 0) and not bmd.get(n, 0)]
    if only_idd:
        print(f"\n  PRESENT ONLY IN IDD: {', '.join(only_idd)}")
        print("  These come from the dashcam source alone, so the joint model")
        print("  learns them at the WRONG viewpoint. Report their elevated")
        print("  performance as unvalidated — no elevated labels exist for them.")

    biggest = max(((bmd.get(n, 0) + idd.get(n, 0)) for n in names), default=0)
    smallest = min(
        ((bmd.get(n, 0) + idd.get(n, 0)) for n in names
         if (bmd.get(n, 0) + idd.get(n, 0)) > 0),
        default=0,
    )
    if smallest and biggest / smallest > 50:
        print(f"\n  CLASS IMBALANCE {biggest / smallest:.0f}:1 (largest to smallest)")
        print("  Inverse-frequency weighting is already specified (PRD §8.4) and")
        print("  FR-D08's per-class support is what keeps this visible in results.")

    print(f"\n  wrote {args.out}/joint.yaml, eval_bmd45.yaml, eval_idd.yaml")
    print("  Train on joint.yaml. Report BOTH eval configs, always, and name")
    print("  which produced each number — a single union mAP hides the trade.")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
