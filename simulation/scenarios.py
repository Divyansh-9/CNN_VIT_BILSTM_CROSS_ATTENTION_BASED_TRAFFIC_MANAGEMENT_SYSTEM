"""Time-varying demand scenarios (P115), beside the three constant regimes.

The regimes `light`, `saturated` and `oversaturated` are files written by
`scripts/build_sumo_demand.py`, and `demand_path` returns exactly the path it
always did for them. A **scenario** is different in kind: a distribution over
demand schedules, where the seed draws one schedule and SUMO's `--seed` draws
the arrivals. Its route file is generated per seed into a gitignored cache.

`pulsed` (PREREGISTRATION_P115.md §1): each approach's demand is piecewise
constant, with segments of a whole number of seconds drawn from
[`d_min`, `d_max`] and levels drawn from `levels`, never repeating the previous
segment's level. Arrivals are SUMO `probability` flows, Bernoulli per second
and per turn movement, so they are stochastic rather than evenly spaced.

Parameters live in `simulation/configs/scenarios.yaml` (NFR-16).
"""

from __future__ import annotations

import hashlib
import json
from pathlib import Path

import numpy as np
import yaml

__all__ = ["CONSTANT_REGIMES", "load_scenarios", "is_scenario", "schedule",
           "routes_xml", "demand_path", "episode_seed", "scenario_hash"]

CONFIG = Path("simulation/configs/scenarios.yaml")
CONSTANT_REGIMES = ("light", "saturated", "oversaturated")
CACHE = Path("data/_demand")
APPROACHES = ("N", "S", "E", "W")


def load_scenarios(path: Path = CONFIG) -> dict:
    return yaml.safe_load(Path(path).read_text(encoding="utf-8"))


def is_scenario(regime: str, config: dict | None = None) -> bool:
    if regime in CONSTANT_REGIMES:
        return False
    config = config if config is not None else load_scenarios()
    if regime not in config or regime == "training_episode_seeds":
        raise ValueError(f"unknown regime or scenario {regime!r}; constant regimes are "
                         f"{CONSTANT_REGIMES}, scenarios are "
                         f"{[k for k in config if k != 'training_episode_seeds']}")
    return True


def scenario_hash(params: dict) -> str:
    """The identity of a parameter set, so a cached route file cannot go stale."""
    blob = json.dumps(params, sort_keys=True).encode("utf-8")
    return hashlib.sha256(blob).hexdigest()[:12]


def schedule(params: dict, seed: int) -> dict[str, list[tuple[int, int, int]]]:
    """Per approach, the `(begin_s, end_s, veh_per_hour)` segments for one seed."""
    levels = [int(v) for v in params["levels"]]
    d_min, d_max = int(params["d_min"]), int(params["d_max"])
    duration = int(params["duration_s"])
    if not (60 <= d_min <= d_max <= 600) or not all(300 <= v <= 1200 for v in levels) \
            or len(set(levels)) < 2:
        raise ValueError(f"parameters outside the P115 bounds: {params}")
    rng = np.random.default_rng([int(seed), int(params["schedule_rng_tag"])])
    out = {}
    for approach in APPROACHES:
        segments, t, previous = [], 0, None
        while t < duration:
            length = int(rng.integers(d_min, d_max + 1))
            level = int(rng.choice([v for v in levels if v != previous]))
            segments.append((t, min(t + length, duration), level))
            t, previous = t + length, level
        out[approach] = segments
    return out


def routes_xml(params: dict, seed: int, name: str = "pulsed") -> str:
    # One definition of the intersection's turn geometry and vehicle mix: the
    # constant regimes' generator. A second copy here would drift.
    from scripts.build_sumo_demand import LEFT_OF, OPPOSITE, RIGHT_OF, TURN_RATIOS

    rows = ['<?xml version="1.0" encoding="UTF-8"?>',
            f"<!-- GENERATED by simulation/scenarios.py — do not edit. scenario={name} "
            f"params={scenario_hash(params)} seed={seed} -->",
            "<routes>"]
    for origin in APPROACHES:
        destinations = {"straight": OPPOSITE[origin], "right": RIGHT_OF[origin],
                        "left": LEFT_OF[origin]}
        for movement in TURN_RATIOS:
            rows.append(f'    <route id="r_{origin}_{movement}" '
                        f'edges="{origin}2C C2{destinations[movement]}"/>')
    flows = []
    for origin, segments in schedule(params, seed).items():
        for k, (begin, end, level) in enumerate(segments):
            for movement, share in TURN_RATIOS.items():
                flows.append((begin, f'    <flow id="f_{origin}_{movement}_{k}" '
                              f'route="r_{origin}_{movement}" type="india_mix" '
                              f'begin="{begin}" end="{end}" '
                              f'probability="{level * share / 3600:.6f}" departLane="free" '
                              f'departSpeed="max" departPosLat="random"/>'))
    # SUMO requires flows sorted by begin time.
    rows += [row for _, row in sorted(flows, key=lambda f: f[0])]
    rows.append("</routes>")
    return "\n".join(rows) + "\n"


def demand_path(net_dir: Path, regime: str, seed: int, *, cache: Path = CACHE,
                config: dict | None = None) -> Path:
    """The route file for one episode.

    A constant regime returns `net_dir/demand_{regime}.rou.xml`, unchanged. A
    scenario returns its per-seed file, generating it on first use.
    """
    if not is_scenario(regime, config):
        return Path(net_dir) / f"demand_{regime}.rou.xml"
    config = config if config is not None else load_scenarios()
    params = config[regime]
    path = Path(cache) / f"{regime}_{scenario_hash(params)}_{int(seed)}.rou.xml"
    if not path.exists():
        path.parent.mkdir(parents=True, exist_ok=True)
        tmp = path.with_suffix(".tmp")
        tmp.write_text(routes_xml(params, seed, regime), encoding="utf-8")
        tmp.replace(path)
    return path


def episode_seed(regime: str, training_seed: int, episode: int,
                 config: dict | None = None) -> int:
    """The SUMO seed of training episode `episode`.

    A constant regime keeps the historical `training_seed + episode`, so
    existing checkpoints stay reproducible. On a scenario the seed IS the
    demand, so episodes are moved clear of the evaluation seeds 0-29 and of
    every design and qualification seed (P115 §4).
    """
    if not is_scenario(regime, config):
        return int(training_seed) + int(episode)
    config = config if config is not None else load_scenarios()
    rule = config["training_episode_seeds"]
    if not 0 <= int(episode) < int(rule["stride"]):
        raise ValueError(f"episode {episode} outside one training seed's block")
    return int(rule["offset"]) + int(rule["stride"]) * int(training_seed) + int(episode)
